import type { FieldDef, FormulaResultType, ObjectDef, PaletteColor, RollupDef } from '@titoforce/shared';

type Extra = Partial<FieldDef>;
type Option = string | [string, PaletteColor];

const field =
  (type: FieldDef['type']) =>
  (apiName: string, label: string, extra: Extra = {}): FieldDef => ({ apiName, label, type, ...extra });

const text = field('text');
const longtext = field('longtext');
const email = field('email');
const phone = field('phone');
const url = field('url');
const number = field('number');
const currency = field('currency');
const percent = field('percent');
const date = field('date');
const datetime = field('datetime');
const checkbox = field('checkbox');
const user = field('user');

const options = (values: Option[]) => values.map((v) => (typeof v === 'string' ? { value: v } : { value: v[0], color: v[1] }));
const picklist = (apiName: string, label: string, values: Option[], extra: Extra = {}): FieldDef => ({ apiName, label, type: 'picklist', options: options(values), ...extra });
const multipicklist = (apiName: string, label: string, values: Option[], extra: Extra = {}): FieldDef => ({
  apiName,
  label,
  type: 'multipicklist',
  options: options(values),
  ...extra,
});
const lookup = (apiName: string, label: string, referenceTo: string, extra: Extra = {}): FieldDef => ({ apiName, label, type: 'lookup', referenceTo, ...extra });
const formula = (apiName: string, label: string, expr: string, formulaType: FormulaResultType, extra: Extra = {}): FieldDef => ({
  apiName,
  label,
  type: 'formula',
  formula: expr,
  formulaType,
  ...extra,
});
const rollup = (apiName: string, label: string, def: RollupDef, extra: Extra = {}): FieldDef => ({ apiName, label, type: 'rollup', rollup: def, ...extra });

const obj = (def: Omit<ObjectDef, 'isCustom'>): ObjectDef => ({ isCustom: false, ...def });

